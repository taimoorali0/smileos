/** Load data from the API; returns [data, reload, loading, error]. */
export function useLoad(url, deps = []) {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const seq = useRef(0);
  const load = useCallback(async () => {
    if (!url) { setData(null); setLoading(false); return; }
    const n = ++seq.current;
    setLoading(true);
    try { const d = await get(url); if (n === seq.current) { setData(d); setError(null); } } catch (e) { if (n === seq.current) setError(e.message); } finally { if (n === seq.current) setLoading(false); }
  }, [url]);
  useEffect(() => { load(); }, [load, ...deps]); // eslint-disable-line react-hooks/exhaustive-deps
  return [data, load, loading, error];
}

