// ===== Modal =====
export function Modal({ title, onClose, children, footer, wide }) {
  useEffect(() => {
    const k = (e) => { if (e.key === 'Escape') onClose(); };
    window.addEventListener('keydown', k);
    return () => window.removeEventListener('keydown', k);
  }, [onClose]);
  return (
    <div className="modal-bg" onMouseDown={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <div className={`modal ${wide ? 'wide' : ''}`} role="dialog" aria-modal="true" aria-label={title}>
        <div className="modal-head"><h2 className="grow">{title}</h2><button type="button" className="btn ghost sm" onClick={onClose} aria-label="Close"><Icon name="x" /></button></div>
        <div className="modal-body">{children}</div>
        {footer && <div className="modal-foot">{footer}</div>}
      </div>
    </div>
  );
}

// ===== Form fields =====
export function Field({ label, children }) { return <label className="field">{label}{children}</label>; }
export function Input({ label, value, onChange, type = 'text', ...rest }) {
  return <Field label={label}><input className="input" type={type} value={value ?? ''} onChange={(e) => onChange(e.target.value)} {...rest} /></Field>;
}
export function Select({ label, value, onChange, options, empty, ...rest }) {
  return (
    <Field label={label}>
      <select className="input" value={value ?? ''} onChange={(e) => onChange(e.target.value)} {...rest}>
        {empty !== undefined && <option value="">{empty}</option>}
        {options.map((o) => <option key={o.value} value={o.value}>{o.label}</option>)}
      </select>
    </Field>
  );
}
export function Check({ label, checked, onChange }) {
  return <label className="check"><input type="checkbox" checked={!!checked} onChange={(e) => onChange(e.target.checked ? 1 : 0)} />{label}</label>;
}

export function Empty({ children }) { return <div className="empty">{children}</div>; }

/** Generic table. columns: [{ key, label, render, className }] */
export function Table({ columns, rows, onRow, selectedId, empty = 'Nothing to show' }) {
  if (!rows) return <Empty>Loading…</Empty>;
  if (!rows.length) return <Empty>{empty}</Empty>;
  return (
    <div className="table-wrap">
      <table className="t">
        <thead><tr>{columns.map((c) => <th key={c.key} className={c.className}>{c.label}</th>)}</tr></thead>
        <tbody>
          {rows.map((r, i) => (
            <tr key={r.id ?? i} className={`${onRow ? 'click' : ''} ${selectedId != null && r.id === selectedId ? 'sel' : ''}`} onClick={onRow ? () => onRow(r) : undefined}>
              {columns.map((c) => <td key={c.key} className={c.className}>{c.render ? c.render(r) : r[c.key]}</td>)}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

